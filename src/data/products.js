export const discount = (mrp, price) => {
  if (!mrp || !price || mrp <= price) return 0
  return Math.round(((mrp - price) / mrp) * 100)
}

export const inr = (n) => {
  if (typeof n !== 'number' || n <= 0) return 'Price on Request'
  return '₹' + n.toLocaleString('en-IN')
}
